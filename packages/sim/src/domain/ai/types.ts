import { Vector3 } from 'three'
import type { Rng } from '../../core/math'
import { taskPoint, type Task } from './tasks'
import { createManoeuvre, type Manoeuvre } from '../flight/aerobatics'

export type AIMode = 'patrol' | 'pursue' | 'attack' | 'break' | 'evade'

/**
 * Чем бот занят — ровно одно на такт. Выбирает арбитр по оценкам (`behaviors.ts`), а не
 * порядок `if` в пилоте: раньше «кто победит» решал номер строки, и бот не мог, например,
 * бросить поручение, когда его самого начали бить.
 */
export type BehaviorId =
  | 'escape' // заряжает прыжок-побег
  | 'hold' // приказ «стой тут»
  | 'keep-back' // приказ «держись в хвосте»
  | 'soft' // автобой по обломку/астероиду
  | 'plan' // план знакомого
  | 'tasks' // очередь поручений и свой промысел
  | 'combat' // бой с целью
  | 'rob' // пират требует груз
  | 'search' // ищет потерянную цель
  | 'dock' // очередь к причалу
  | 'rejoin' // эскорт отстал — догоняет нанимателя
  | 'patrol' // ничего не надо — кружит у дома

/**
 * Фаза стыковки трафика. null — корабль не стыкуется вовсе.
 *   inbound  — заходит на причал (или ждёт очередь, если он занят);
 *   berthed  — стоит у причала положенное время;
 *   done     — отчалил и уходит прочь, дальше живёт обычным трафиком.
 */
export type DockPhase = 'inbound' | 'berthed' | 'done' | null

/**
 * Память пилота-бота. Он не двигает корабль — он заполняет тот же ShipControls,
 * что и игрок мышью. Всё, что он умеет, физически доступно и тебе.
 */
export interface AIState {
  /** Текущее поведение, выбранное арбитром. */
  behavior: BehaviorId
  mode: AIMode
  /** Кого атакуем. null — цели нет. Выбирается по фракции, а не «это всегда игрок»:
   *  иначе полиция никогда не подерётся с пиратами. */
  targetId: number | null
  /**
   * ПРИКАЗ: атаковать именно этого и никого другого. null — пилот выбирает сам.
   *
   * Так работает автобой на корабле игрока: тот же пилот, та же физика, но цель
   * ему назначена, а не выбрана. Без приказа он в такте размышления переключился бы
   * на ближайшего врага, и «автобой по захваченной цели» перестал бы означать то,
   * что написано на кнопке.
   */
  orderedTargetId: number | null
  /**
   * Мягкая цель автобоя (обломок / астероид). Не корабль — у неё нет `ShipEntity`,
   * поэтому приказ живёт отдельно от `orderedTargetId`. null — бьём борт или цели нет.
   */
  orderedSoft: { kind: 'pod' | 'asteroid' | 'fixture'; id: number } | null
  /** Куда сейчас летим: патрульная точка или точка отрыва. */
  waypoint: Vector3
  /** Район патрулирования. Бот не улетает из него без причины. */
  home: Vector3

  /** До следующего пересмотра решения. Это и есть время реакции. */
  thinkTimer: number
  /**
   * Длина ТЕКУЩЕГО такта размышления, с. Решения с темпом в секундах (пуск ракеты, побег)
   * переводят темп в шанс именно за этот промежуток — иначе пилот, думающий реже,
   * решался бы реже, и выучка незаметно меняла бы частоту, а не только реакцию.
   */
  thinkSpan: number
  /** Сколько бот уже в текущем режиме. */
  modeTimer: number

  /** Личный сдвиг фазы: без него звено маневрирует синхронно, как балет. */
  phase: number

  /** Смещение точки прицеливания — «рука дрожит». */
  aimJitter: Vector3
  aimJitterTimer: number

  wantsFire: boolean
  /** Решение о пуске принимается в такте размышления, а не каждый шаг физики. */
  wantsMissile: boolean
  /** Секунд до следующего возможного пуска. Иначе бот высыпает всю пусковую разом. */
  missileCooldown: number
  /** Жать ли ПРО. Тоже решение такта размышления: бот видит ракету не мгновенно. */
  wantsEcm: boolean
  /**
   * Защёлка крейсера, о которой просит пилот: множитель > 1 — держать его, иначе крейсер
   * отпущен. Сбрасывается каждый шаг: просьба живёт, пока поведение её повторяет.
   */
  cruiseHold: number
  /**
   * Наибольший id ракеты, о которой бот уже решил, сбивать ли её. Решение — одно на ракету:
   * кость за такт копила бы шанс со временем подлёта (см. `AI.ECM_CHANCE`).
   */
  ecmSeenId: number

  /**
   * ЛИЧНЫЕ враги: id бортов, с которыми у этого пилота война помимо фракций. Пират,
   * которому торговец отказал в грузе, и торговец, на которого напали, — враги друг другу,
   * хотя их фракции не воюют. Взаимно: достаточно записи у одного из двоих.
   */
  foes: number[]
  /**
   * Память о цели, потерянной из виду (зашла за планету, ушла за радиус). Пока свежа —
   * бот идёт туда, где видел её в последний раз, а не забывает в тот же миг.
   */
  lastSeenId: number | null
  lastSeenPos: Vector3
  lastSeenVel: Vector3
  lastSeenAt: number

  /** Кого пират собрался грабить. null — никого. */
  preyId: number | null
  /** Когда выставлено требование сбросить груз (`world.time`); −1 — ещё не требовал. */
  demandAt: number

  /**
   * Кого сопровождает. null — никого.
   *
   * Наёмник держится рядом с нанимателем и бьёт того, кого тот захватил. Своей
   * цели он не выбирает: он не второй пилот, а ведомый.
   */
  escortOf: number | null
  /**
   * Выучка, 0..1. Единица — обычный пилот.
   *
   * Слабость моделируется ЧЕСТНО: медленнее реакция, шире разброс. Урон и
   * угловая скорость у наёмника те же, что у всех, — он проигрывает решением,
   * а не заниженным оружием. Ровно этим правилом живут и пираты.
   */
  skill: number
  /**
   * Кто ведёт борт, если не его хозяин: в автобое игрока штурвал у ВТОРОГО ПИЛОТА, и выучку
   * задаёт его ранг, а не ранг игрока. `null` — ведёт сам (`ship.rank`).
   */
  pilotRank: number | null
  /**
   * Фигура пилотажа — та же, что у игрока на двойном тапе (`aerobatics.ts`), тем же кодом.
   * Бот пускает её решением в такте размышления, не привилегией: ни тангаж, ни крен у него
   * не быстрее, чем у тебя на SS.
   */
  manoeuvre: Manoeuvre
  /** Когда (`world.time`, с) начат последний разворот — для `AI.REVERSAL_INTERVAL`. */
  reversalAt: number
  /**
   * Бой по очереди: цель пала — брать следующего врага на локаторе (`retargetAutofight`).
   * Нет — после цели штурвал возвращается.
   */
  chainFoes: boolean

  /** Стыкуется ли к причалу и на какой стадии. null — обычный трафик. */
  dock: DockPhase
  /** Секунд у причала до отчаливания. Тикает только в фазе `berthed`. */
  dockTimer: number
  /**
   * К КАКОЙ станции стыкуется — запомнена в миг захода. Прежде станцию выбирали заново каждый
   * такт как ближайшую к игроку, и заходящий бот разворачивался через всю систему к станции,
   * у которой игрок оказался. null — ещё не выбрал (или не стыкуется).
   */
  dockStationId: number | null

  /**
   * Дремлет на палубе платформы-гнезда. Пока true — пилот не двигает корабль,
   * не выбирает цель и не стреляет: его можно вырезать по одному, и он не
   * шевельнётся. Будит гнездо `stepPlatforms`, снимая флаг разом со всего звена.
   */
  dormant: boolean

  /** Стоящий приказ игрока СВОЕМУ автоботу. См. `AICommand`. */
  command: AICommand

  /**
   * Очередь ПОРУЧЕНИЙ, взятых в разговоре (см. `tasks.ts`). Пустая — бот действует по
   * приказу/эскорту как обычно; непустая — уходит исполнять её (сбор груза, встреча, позже
   * перелёт/покупка/разговор), голова очереди — текущая задача. Приоритет над боем: послал
   * за делом — он делом и занят, а не висит в свалке.
   */
  tasks: Task[]

  /**
   * Обратный отсчёт зарядки прыжка-побега, с. Отрицательный — не заряжает. Пока
   * тикает, бот уходит от угрозы и уязвим; дошёл до нуля — уходит из системы.
   */
  warpTimer: number

  /**
   * Претензия к игроку за попадания: счётчик засчитанных попаданий подряд, 0 — нет.
   * Пока > 0 и борт ещё не враг — пилот вызывает по связи и ждёт объяснений (это
   * читает UI). На `GRIEVANCE.HOSTILE_HITS` он становится враждебным честно. Гаснет
   * сам через `GRIEVANCE.COOLDOWN` без новых попаданий. Разряд — словом или кнопкой.
   */
  grievance: number
  /** `world.time` последнего засчитанного попадания. Для дебаунса и угасания претензии. */
  grievanceAt: number
  /** Когда началась текущая претензия — для таймера ответного огня. */
  grievanceSince: number
  /** Засчитанные попадания игрока в текущей серии (включая прощённые). */
  strikeCount: number
  /**
   * Напряжённость РАЗГОВОРА с командиром: угрозы и хамство копят, лесть и извинение гасят,
   * остывает минутами (`DIALOGUE.TENSION`). Отдельно от `grievance` — тот про попадания и
   * живёт секундами боя. Реакцию на разрыве решает `dialogue/temper.ts`.
   */
  tension: number
}

/**
 * Приказ игрока своему автоботу — собственному автобою или нанятому эскорту.
 *
 * Это команды ПОСЛУШАНИЯ, а не уговоры: их отдают напрямую (кнопкой из выпадушки
 * или голосом), потому что бот уже на твоей стороне и решать ему нечего. Уговорить
 * ЧУЖОГО что-то сделать — дело разговора (LLM) или скриптового взвешивания персоны,
 * а не этого поля.
 *
 *   default   — бот действует сам: эскорт бьёт цель, захваченную нанимателем;
 *   attack    — бить/догонять именно `orderedTargetId` (конкретный корабль);
 *   engageAll — свободный огонь по всем враждебным вокруг;
 *   hold      — стоять на месте, в бой не лезть, пока игрок отлучился;
 *   standDown — прекратить огонь, никого не атаковать, держаться рядом;
 *   keepBack  — держаться в хвосте и уходить от боя, беречь себя и груз.
 */
export type AICommand = 'default' | 'attack' | 'engageAll' | 'hold' | 'standDown' | 'keepBack'

export function createAIState(home: Vector3, rng: Rng): AIState {
  return {
    behavior: 'patrol',
    mode: 'patrol',
    targetId: null,
    orderedTargetId: null,
    orderedSoft: null,
    waypoint: home.clone(),
    home: home.clone(),
    thinkTimer: rng() * 0.12,
    thinkSpan: 0.12,
    modeTimer: 0,
    phase: rng() * Math.PI * 2,
    aimJitter: new Vector3(),
    aimJitterTimer: 0,
    wantsFire: false,
    wantsMissile: false,
    // Первая ракета не летит в первые же секунды боя: дай игроку осмотреться.
    missileCooldown: 6,
    wantsEcm: false,
    cruiseHold: 0,
    ecmSeenId: -1,
    foes: [],
    lastSeenId: null,
    lastSeenPos: new Vector3(),
    lastSeenVel: new Vector3(),
    lastSeenAt: -1e9,
    preyId: null,
    demandAt: -1,
    escortOf: null,
    skill: 1,
    pilotRank: null,
    manoeuvre: createManoeuvre(),
    reversalAt: -1e9,
    chainFoes: false,
    dock: null,
    dockTimer: 0,
    dockStationId: null,
    dormant: false,
    command: 'default',
    tasks: [],
    warpTimer: -1,
    grievance: 0,
    grievanceAt: -1e9,
    grievanceSince: -1e9,
    tension: 0,
    strikeCount: 0,
  }
}

/**
 * Сдвинуть все ТОЧКИ пилота вместе с миром при перецентровке плавающего начала
 * (`maybeShiftOrigin`). Корабли сдвигаются, а их дом, путевая точка, память о цели и точки
 * поручений — раньше нет: после сдвига бот правил «домой» в пустоту за десятки километров.
 */
export function shiftAIState(ai: AIState, shift: Vector3): void {
  ai.home.add(shift)
  ai.waypoint.add(shift)
  ai.lastSeenPos.add(shift)
  for (const t of ai.tasks) taskPoint(t)?.add(shift)
}
