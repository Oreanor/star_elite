  variant: number
  pos: Vector3
  /** Ось кувырка — своя у каждой, оттого они не крутятся строем. */
  spinAxis: Vector3
  /** Кувырок, рад/с. Медленный: это статуя, а не станция. */
  spin: number
  /** Габарит, м. Статуя — километры: её видно с любого конца системы. */
  radius: number
