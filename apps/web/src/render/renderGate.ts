/**
 * Пауза отрисовки 3D, пока кадр всё равно закрыт.
 *
 * Отрисовка — это не только рисование: на первом показе объекта three компилирует шейдер
 * и ждёт его готовности, заливает текстуры в видеокарту, переводит небо в кубическую карту.
 * Всё это — главный поток. Когда оно попадает на «вжух» титула, CSS-анимации, которые ведёт
 * React (варп-штрихи, гаснущая пыль), стартуют с опозданием и рвутся, а те, что крутит
 * композитор, идут ровно — отсюда «одни резче других». Пока кадр закрыт непрозрачным титулом,
 * рисовать незачем: держим паузу, а тяжёлое делаем там, где его не видно.
 *
 * Причины независимы: прогрев сцены (`warmup`) и флориш титула (`flourish`) снимают каждый
 * свою, и кадр идёт, только когда не держит никто.
 */
export type RenderHold = 'warmup' | 'flourish'

const holds = new Set<RenderHold>()

export function holdRender(reason: RenderHold, on: boolean): void {
  if (on) holds.add(reason)
  else holds.delete(reason)
}

export function renderHeld(): boolean {
  return holds.size > 0
}
