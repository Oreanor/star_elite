import { describe, expect, it } from 'vitest'
import { paintBand } from './nebula'

describe('процедурное небо', () => {
  /**
   * Пойманное: заглушка неба строилась 5.5 с главного потока на старте игры — каждый вызов
   * шума заводил генератор с тем же зерном и набивал таблицу фаз заново, 67 млн бросков
   * `rng` на картинку. Заставка в это время стояла колом, хотя через миг заглушку сменит
   * `sky/N.webp`. Теперь шум разложен на столбцы и строки и строится за десятки миллисекунд.
   *
   * Порог взят с запасом на медленную машину, а не подогнан: прежняя версия не влезала
   * в него и близко, нынешняя укладывается раз в десять.
   */
  it('строится быстрее полусекунды — заставка не ждёт заглушку', () => {
    const data = new Uint8ClampedArray(1024 * 512 * 4)
    const start = performance.now()
    paintBand(data)
    expect(performance.now() - start).toBeLessThan(500)
  })
})
