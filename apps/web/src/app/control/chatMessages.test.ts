import { describe, expect, it } from 'vitest'
import { chatMessages } from './chatMessages'

describe('реплики канала → сообщения модели', () => {
  // Пойманный баг: строки исхода («Зачислено: 100 кр») выбрасывались, модель видела одни слова.
  // Перевод прошёл — а бот через пару реплик «не помнил»; сказал «принял» без перевода — и не
  // узнал, что ничего не пришло. Факт канала обязан дойти до модели, по порядку событий.
  it('факт канала доходит до модели в следующей реплике командира', () => {
    const msgs = chatMessages(
      [
        { who: 'you', text: 'держи 100 кредитов' },
        { who: 'them', text: 'Принял. Спасибо.' },
        { who: 'system', text: 'Зачислено: 100 кр' },
        { who: 'you', text: 'помнишь, сколько я дал?' },
      ],
      'а сейчас?',
      'ФАКТ КАНАЛА',
    )
    expect(msgs.map((m) => m.role)).toEqual(['user', 'assistant', 'user', 'user'])
    expect(msgs[2]!.content).toBe('[ФАКТ КАНАЛА: Зачислено: 100 кр]\nпомнишь, сколько я дал?')
  })

  it('факт после последней реплики бота ложится в текущую реплику командира', () => {
    const msgs = chatMessages(
      [
        { who: 'them', text: 'Принял монетку.' },
        { who: 'system', text: 'Зачислено: 1 кр' },
      ],
      'видишь?',
      'ФАКТ КАНАЛА',
    )
    expect(msgs.at(-1)!.content).toBe('[ФАКТ КАНАЛА: Зачислено: 1 кр]\nвидишь?')
  })
})
