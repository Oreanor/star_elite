/**
 * Адрес файла из `public/` с учётом пути, по которому выложена игра.
 *
 * На домашнем сервере игра живёт не в корне хоста, а по `/star_elite/` (Caddy делит один
 * адрес между несколькими играми). Vite сам добавляет этот путь к бандлам, `index.html` и
 * `url()` в CSS, но строки в коде не трогает: голое `'/models/…'` ушло бы в корень хоста,
 * то есть в чужое приложение. Поэтому каждый путь к `public/` идёт через эту функцию.
 * В разработке и в тестах `BASE_URL` равен `/`, и путь остаётся как был.
 */
export function asset(path: string): string {
  return import.meta.env.BASE_URL + path.replace(/^\/+/, '')
}
