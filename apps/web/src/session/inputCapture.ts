/**
 * ЗАХВАТ ВВОДА: кто-то поверх игры забрал клавиши себе.
 *
 * Нужен, чтобы штурвал не спорил с инструментом. Пока редактор оснастки правит сопла,
 * Ctrl — это модификатор сдвига вдоль корпуса, а не ручник: иначе каждая правка глубины
 * дёргала бы корабль, и подстраивать устье пришлось бы на торможении.
 *
 * Флаг живёт ЗДЕСЬ, а не в самом редакторе, из-за направления зависимостей. Редактор —
 * инструмент рендера (он правит реестр геометрии), а контроллер игрока — состояние сеанса,
 * то есть слой НИЖЕ. Спрашивай контроллер прямо у редактора — и управление начало бы
 * зависеть от сцены. Захватчик заявляет о себе сам, а читают его снизу.
 */

let captured = false

/** Заявить (или снять) захват. Зовёт тот, кто забирает ввод: редактор, отладочный режим. */
export function setInputCaptured(value: boolean): void {
  captured = value
}

/** Забран ли ввод кем-то поверх игры. */
export function inputCaptured(): boolean {
  return captured
}
